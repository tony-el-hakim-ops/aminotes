import 'dart:io';

import 'package:aminotes/aminotes.dart';
import 'package:aminotes_example/playground.dart';
import 'package:flutter_test/flutter_test.dart';

// Writes the code the playground generates for every preset into
// build/playground_code/, wrapped in functions, so `flutter analyze` can check
// it compiles against the package (see tool/check_playground_code.sh).
void main() {
  test('the playground generates code for every preset', () {
    final out = Directory('build/playground_code')..createSync(recursive: true);
    final buffer = StringBuffer()
      ..writeln('// Generated by test/playground_code_test.dart.')
      ..writeln('// ignore_for_file: unused_element, prefer_const_constructors')
      ..writeln("import 'dart:math';")
      ..writeln("import 'package:aminotes/aminotes.dart';")
      ..writeln("import 'package:flutter/material.dart';");
    for (final (i, design) in playgroundPresets.indexed) {
      for (final items in [AminotesToolbarItem.compact, const <AminotesToolbarItem>[]]) {
        final code = generatePlaygroundCode(design, items);
        expect(code, contains('AminotesEditor('));
        final widgets = code.split(',\n\n');
        buffer
          ..writeln('List<Widget> _preset$i${items.isEmpty ? 'NoToolbar' : ''}(AminotesController controller) => [')
          ..writeln(widgets.first.trim().replaceAll(RegExp(r'^//.*\n', multiLine: true), '').trim())
          ..writeln(',');
        if (items.isNotEmpty) buffer.writeln(widgets.last.trim());
        buffer.writeln('];');
      }
    }
    File('${out.path}/generated.dart').writeAsStringSync(buffer.toString());
  });
}
